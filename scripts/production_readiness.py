from quantforge.infrastructure import ProductionReadinessPlatform


def main() -> None:
    report = ProductionReadinessPlatform().run_report()

    print("Production Readiness")
    print()
    print("Health")
    print(f"{report.healthy_services}/{len(report.services)} services healthy")
    print()
    print("Heartbeats")
    print(f"{len(report.heartbeats)} received")
    print()
    print("Metrics")
    print(f"{len(report.metrics)} Prometheus samples")
    print()
    print("Structured Logs")
    print(f"{len(report.logs)} JSON records")
    print()
    print("Tracing")
    print(f"{len(report.traces)} spans")
    print()
    print("Alerts")
    print(f"{report.critical_alerts} critical")
    print()
    print("Recovery")
    print("READY" if all(action.completed for action in report.recovery_actions) else "BLOCKED")
    print()
    print("State Sync")
    print("REPAIRED" if all(repair.repaired for repair in report.synchronization.repairs) else "BLOCKED")
    print()
    print("Disaster Recovery")
    print(f"RPO {report.disaster_recovery.rpo_minutes}m / RTO {report.disaster_recovery.rto_minutes}m")
    print()
    print("Backups")
    print("RESTORED" if report.backup_report.restoration_verified else "NOT VERIFIED")
    print()
    print("Pre-Market")
    print(f"{sum(checkpoint.status.value == 'PASS' for checkpoint in report.pre_market_checkpoints)}/{len(report.pre_market_checkpoints)} checks pass")
    print()
    print("Failure Injection")
    print(f"{sum(result.recovered for result in report.failure_injection_results)}/{len(report.failure_injection_results)} recovered")
    print()
    print("Latency")
    print("PASS" if all(benchmark.passed for benchmark in report.performance_benchmarks) else "FAIL")
    print()
    print("Runbooks")
    print(f"{len(report.runbooks)} ready")
    print()
    print("Capital Protection")
    print("YES" if report.capital_protected and report.duplicate_order_guard else "NO")


if __name__ == "__main__":
    main()
